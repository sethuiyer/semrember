#!/usr/bin/env python3
"""Generate src/unicode_tables.cr from the C library's Unicode tables.

    python3 tools/gen_unicode_tables.py <path-to-src/unicode_data.h>

The C library already carries the tables this port needs: the full Unicode
lowercase mapping (2,866 entries, including the multi-codepoint cases), the
combining-mark ranges to strip, the punctuation ranges, and the cased /
case-ignorable ranges that the final-sigma rule needs.

Porting those tables rather than re-deriving them from Crystal's built-ins is
deliberate.  Crystal's `String#downcase` maps codepoints independently, so it
turns "ΣΣ" into "σσ" where Python's `str.lower()` gives "σς" — the contextual
final-sigma rule.  The C library implements that rule explicitly with the
cased tables below; sharing the tables makes the two agree by construction
instead of by luck.

The output is generated, checked in, and byte-stable: re-running it must
produce an identical file.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HEADER = """# unicode_tables.cr — generated by tools/gen_unicode_tables.py.  Do not edit.
#
# Unicode tables shared with the C implementation so that both agree on
# lowercasing, mark stripping and punctuation classification.

module Semrember
  module Unicode
"""

FOOTER = """  end
end
"""


def parse_lower_simple(text: str) -> list[tuple[int, list[int]]]:
    """Parse SR_LOWER: {0xCP, {0xA, 0xB, 0xC}, N}"""
    m = re.search(r"static const sr_lower_entry SR_LOWER\[\] = \{(.*?)\n\};", text, re.S)
    if not m:
        raise SystemExit("SR_LOWER not found")
    entries = []
    pat = re.compile(
        r"\{0x([0-9A-Fa-f]+),\s*\{\s*(0x[0-9A-Fa-f]+|0)\s*,\s*(0x[0-9A-Fa-f]+|0)\s*,\s*(0x[0-9A-Fa-f]+|0)\s*\},\s*(\d+)\}"
    )
    for cp, a, b, c, n in pat.findall(m.group(1)):
        hx = lambda t: int(t, 16) if t.startswith("0x") else int(t)
        vals = [hx(a)]
        cnt = int(n)
        if cnt > 1:
            vals.append(hx(b))
        if cnt > 2:
            vals.append(hx(c))
        entries.append((int(cp, 16), vals))
    return entries


def parse_ranges(text: str, name: str) -> list[tuple[int, int]]:
    m = re.search(
        r"static const uint32_t %s\[\]\[2\] = \{(.*?)\n\};" % name, text, re.S
    )
    if not m:
        raise SystemExit(f"{name} not found")
    out = []
    for a, b in re.findall(r"\{0x([0-9A-Fa-f]+),\s*0x([0-9A-Fa-f]+)\}", m.group(1)):
        out.append((int(a, 16), int(b, 16)))
    return out


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    src = Path(sys.argv[1])
    text = src.read_text()

    lower = parse_lower_simple(text)
    mn = parse_ranges(text, "SR_MN_RANGES")
    punct = parse_ranges(text, "SR_PUNCT_RANGES")
    cased = parse_ranges(text, "SR_CASED_RANGES")
    ignorable = parse_ranges(text, "SR_CASE_IGNORABLE_RANGES")

    out = [HEADER]
    out.append("  # Full lowercase mapping (Unicode SpecialCasing), up to 3 codepoints.")
    out.append("  LOWER = {")
    for cp, vals in lower:
        out.append(
            "    0x%X_u32 => [%s]," % (cp, ", ".join("0x%X_u32" % v for v in vals))
        )
    out.append("  }")
    out.append("")
    for name, table, doc in (
        ("MN_RANGES", mn, "Combining marks (category Mn) — stripped after decomposition."),
        ("PUNCT_RANGES", punct, "Punctuation (all category P) — isolated by the tokenizers."),
        ("CASED_RANGES", cased, "Cased characters — used by the final-sigma rule."),
        ("CASE_IGNORABLE_RANGES", ignorable, "Case-ignorable characters — used by the final-sigma rule."),
    ):
        out.append("  # %s" % doc)
        out.append("  %s = [" % name)
        for a, b in table:
            out.append("    {0x%X_u32, 0x%X_u32}," % (a, b))
        out.append("  ]")
        out.append("")
    out.append(FOOTER)

    dst = Path(__file__).resolve().parent.parent / "src" / "unicode_tables.cr"
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("\n".join(out))
    print(
        f"wrote {dst}  ({len(lower)} lowercase entries, "
        f"{len(mn)} Mn ranges, {len(punct)} punct ranges, "
        f"{len(cased)} cased ranges, {len(ignorable)} case-ignorable ranges)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
